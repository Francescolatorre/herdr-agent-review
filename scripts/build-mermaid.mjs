// In a build directory install beautiful-mermaid@1.1.3, elkjs@0.11.1,
// entities@7.0.1 and esbuild@0.28.2. Pass that directory as the argument.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { resolve } from "node:path";

const buildDirectory = resolve(process.argv[2] ?? ".");
const require = createRequire(resolve(buildDirectory, "package.json"));
const { build } = require("esbuild");
const { outputFiles } = await build({
  entryPoints: [resolve(buildDirectory, "node_modules/beautiful-mermaid/dist/index.js")],
  bundle: true, format: "esm", platform: "neutral", target: "es2018",
  minify: true, write: false,
});
let source = outputFiles[0].text;

function adapt(before, after) {
  if (source.split(before).length !== 2) throw new Error(`Unexpected ELK bundle near ${before}`);
  source = source.replace(before, after);
}

// The ELK worker is synchronous here. Give its GWT code the built-ins that
// Herdr's window facade does not expose. Leave global objects alone.
adapt('var A;typeof window!="undefined"?A=window:typeof T!="undefined"?A=T:typeof self!="undefined"&&(A=self);',
  "var A={Math,Array,Date,Error,Function};");
adapt("s.toString=function(){return this.Ib()}",
  'Object.defineProperty(s,"toString",{value:function(){return this.Ib()},writable:true,configurable:true})');
adapt("A.Error.stackTraceLimit=Error.stackTraceLimit=64,!0", "!0");

const output = new URL("../mods/reviewer-files/renderer.bundle.js", import.meta.url);
writeFileSync(output, "// Generated by scripts/build-mermaid.mjs. See the licenses directory.\n" + source);

for (const [pkg, filename] of [["beautiful-mermaid", "LICENSE"], ["elkjs", "LICENSE.md"], ["entities", "LICENSE"]]) {
  writeFileSync(new URL(`../mods/reviewer-files/licenses/${pkg}.txt`, import.meta.url),
    readFileSync(resolve(buildDirectory, "node_modules", pkg, filename)));
}
