// Rebuilds mods/reviewer/renderer.bundle.js (the Mermaid renderer) and the
// license files in mods/reviewer/licenses/ from the exact versions pinned in
// scripts/mermaid-build/package-lock.json.
//
//   cd scripts/mermaid-build && npm ci && cd ../.. && node scripts/build-mermaid.mjs
//
// Pass another directory (with node_modules installed from the same lockfile)
// as the argument to build elsewhere. `--check` builds in memory and fails when
// the committed bundle differs, so CI can prove the bundle matches its inputs.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { resolve } from "node:path";

const args = process.argv.slice(2);
const check = args.includes("--check");
const buildDirectory = resolve(args.find((arg) => !arg.startsWith("--")) ?? new URL("./mermaid-build", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
const require = createRequire(resolve(buildDirectory, "package.json"));
const { build } = require("esbuild");
const { outputFiles } = await build({
  entryPoints: [resolve(buildDirectory, "node_modules/beautiful-mermaid/dist/index.js")],
  bundle: true, format: "esm", platform: "neutral", target: "es2018",
  minify: true, write: false, legalComments: "none",
});
let source = outputFiles[0].text;

function adapt(before, after) {
  if (source.split(before).length !== 2) throw new Error(`Unexpected ELK bundle near ${before}`);
  source = source.replace(before, after);
}

// The ELK worker is synchronous here. Give its GWT code the built-ins that
// Herdr's window facade does not expose. Leave global objects alone.
adapt('var A;typeof window!="undefined"?A=window:typeof T!="undefined"?A=T:typeof self!="undefined"&&(A=self);',
  "var A={Math,Array,Date,Error,Function};");
adapt("s.toString=function(){return this.Ib()}",
  'Object.defineProperty(s,"toString",{value:function(){return this.Ib()},writable:true,configurable:true})');
adapt("A.Error.stackTraceLimit=Error.stackTraceLimit=64,!0", "!0");

// Herdr's shell has no setTimeout (it throws). ELK defers its start-up messages with
// setTimeout(fn, 0), which the renderer queues and replays; run that queue while the
// replacement is still installed, so messages sent during the replay are queued too.
adapt("globalThis.setTimeout=v,g.forEach(E=>E())", "(()=>{for(;g.length;)g.shift()()})(),globalThis.setTimeout=v");

const output = new URL("../mods/reviewer/renderer.bundle.js", import.meta.url);
const bundle = "// Generated by scripts/build-mermaid.mjs from scripts/mermaid-build/package-lock.json. See licenses/.\n" + source;
const licenses = [["beautiful-mermaid", "LICENSE"], ["elkjs", "LICENSE.md"], ["entities", "LICENSE"]]
  .map(([pkg, file]) => [pkg, readFileSync(resolve(buildDirectory, "node_modules", pkg, file), "utf8")]);

if (check) {
  const same = readFileSync(output, "utf8") === bundle
    && licenses.every(([pkg, text]) => readFileSync(new URL(`../mods/reviewer/licenses/${pkg}.txt`, import.meta.url), "utf8") === text);
  if (!same) { console.error("mods/reviewer/renderer.bundle.js or licenses/ differ from a fresh build"); process.exit(1); }
  console.log("renderer bundle matches its pinned inputs");
} else {
  mkdirSync(new URL("../mods/reviewer/licenses/", import.meta.url), { recursive: true });
  writeFileSync(output, bundle);
  for (const [pkg, text] of licenses) writeFileSync(new URL(`../mods/reviewer/licenses/${pkg}.txt`, import.meta.url), text);
  console.log(`wrote ${output.pathname} (${bundle.length} bytes)`);
}
